export type Locale = "ar" | "en"

export type LocalizedString = {
  ar: string
  en: string
}

export function t(value: LocalizedString | string, locale: Locale): string {
  if (typeof value === "string") return value
  return value[locale] || value.ar || value.en || ""
}

export type Feature = {
  icon: string
  title: LocalizedString
  body: LocalizedString
}

export type Shot = {
  src: string
  caption: LocalizedString
}

export type Detail = {
  src: string
  srcEn?: string
  icon: string
  label: LocalizedString
  caption: LocalizedString
  focus: string // CSS object-position for cropping into the relevant region
}

